/** 已内置图标名清单（字典序，便于自检/文档/下游引用校验） */
export const ICON_NAMES = Object.freeze(Object.keys(ICON_PATHS).sort());

// ---- 统一 SVG 规格（Tabler 原生） ----
const VIEW_BOX = "0 0 24 24";
const BASE_CLASS = "y-icon";
const DEFAULT_SIZE = 20;
const DEFAULT_STROKE = 1.75;

/** 属性值转义：label/class 含引号或尖括号时不破坏 SVG 结构 */
function escapeAttr(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/** 数字选项归一：非法/非正数回退默认值 */
function pickNumber(value, fallback) {
  const n = Number(value);
  return Number.isFinite(n) && n > 0 ? n : fallback;
}

/**
 * 生成内联 SVG 字符串。
 * @param {string} name 图标名（见 ICON_NAMES）
 * @param {{ size?: number, class?: string, stroke?: number, label?: string }} [opts]
 *   size  宽高像素（默认 20）；class 附加 class（基础类 y-icon 始终保留）；
 *   stroke 描边宽度（默认 1.75）；label 有值时 role="img" + aria-label，
 *   无值时 aria-hidden="true"（纯装饰）。
 * @returns {string} SVG 字符串；未知图标名返回 ""（占位安全，不抛错、不破坏渲染）
 */
export function icon(name, opts = {}) {
  const paths = Object.prototype.hasOwnProperty.call(ICON_PATHS, name)
    ? ICON_PATHS[name]
    : null;
  if (!paths) return "";

  const size = pickNumber(opts.size, DEFAULT_SIZE);
  const stroke = pickNumber(opts.stroke, DEFAULT_STROKE);
  const classes = opts.class ? `${BASE_CLASS} ${opts.class}` : BASE_CLASS;
  const a11y = opts.label
    ? ` role="img" aria-label="${escapeAttr(opts.label)}"`
    : ' aria-hidden="true"';

  const body = paths.map((d) => `<path d="${d}" />`).join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="${VIEW_BOX}" fill="none" stroke="currentColor" stroke-width="${stroke}" ` +
    `stroke-linecap="round" stroke-linejoin="round" class="${escapeAttr(classes)}"` +
    `${a11y} focusable="false">${body}</svg>`
  );
}

/**
 * 生成真实 SVGElement（需要挂 DOM / 绑定事件 / 复用节点时用；字符串拼接用 icon()）。
 * 无 DOM 环境（node 单测 / 非浏览器）返回 null；未知图标名同样返回 null。
 * @returns {SVGElement|null}
 */
export function iconEl(name, opts = {}) {
  const markup = icon(name, opts);
  if (!markup) return null;
  if (typeof document === "undefined") return null;
  const host = document.createElement("template");
  host.innerHTML = markup;
  return host.content ? host.content.firstElementChild : null;
}
